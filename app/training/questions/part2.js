export function parsePart2Questions() {
  const regex = /^(\d+)\.\s+(.*?)\nA\)\s+(.*?)\nB\)\s+(.*?)\nC\)\s+(.*?)\nD\)\s+(.*?)\n\*\*Answer:\s+([A-D])\*\*/gm;
  const questions = [];
  let match;
  while ((match = regex.exec(part2QuestionsRaw)) !== null) {
    questions.push({
      id: parseInt(match[1]),
      question: match[2].trim(),
      options: {
        A: match[3].trim(),
        B: match[4].trim(),
        C: match[5].trim(),
        D: match[6].trim()
      },
      answer: match[7]
    });
  }
  return questions;
}
